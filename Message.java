package mycompany.project1;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Iterator;
import java.util.List;
import java.util.concurrent.ThreadLocalRandom;
import java.util.regex.Matcher;
import java.util.regex.Pattern;


public class Message {

    public static final int MAX_LENGTH = 250;

    
    private static final Pattern CELL_PATTERN = Pattern.compile("^\\+[0-9]{1,3}[0-9]{1,10}$");

    
    private static final String JSON_STR = "\"((?:[^\"\\\\]|\\\\.)*)\"";
    private static final Pattern JSON_ENTRY = Pattern.compile(
            "\"messageID\"\\s*:\\s*" + JSON_STR + "\\s*,\\s*"
          + "\"messageNumber\"\\s*:\\s*(\\d+)\\s*,\\s*"
          + "\"messageHash\"\\s*:\\s*" + JSON_STR + "\\s*,\\s*"
          + "\"recipient\"\\s*:\\s*" + JSON_STR + "\\s*,\\s*"
          + "\"message\"\\s*:\\s*" + JSON_STR,
          Pattern.DOTALL);

    
    private static final List<Message> sentMessages = new ArrayList<>();
    private static final List<Message> disregardedMessages = new ArrayList<>();
    private static final List<Message> storedMessages = new ArrayList<>();
    private static final List<String> messageHashes = new ArrayList<>();
    private static final List<String> messageIDs = new ArrayList<>();

    private static int messageCounter = 0;          // autogenerated "message number"
    private static Path storagePath = Paths.get("messages.json");
    private static String sender = "Unknown sender";

    private final String messageID;
    private final int messageNumber;
    private final String recipient;
    private final String messageText;
    private final String messageHash;


    public Message(String recipient, String messageText) {
        this(generateMessageID(), messageCounter++, recipient, messageText);
    }


    public Message(String messageID, int messageNumber, String recipient, String messageText) {
        this.messageID = messageID;
        this.messageNumber = messageNumber;
        this.recipient = recipient;
        this.messageText = messageText;
        this.messageHash = createMessageHash();
    }


    public boolean checkMessageID() {
        return messageID != null && messageID.length() <= 10;
    }


    public String checkRecipientCell() {
        return validateRecipient(recipient);
    }

    public static boolean isValidRecipient(String cell) {
        return cell != null && CELL_PATTERN.matcher(cell).matches();
    }

    public static String validateRecipient(String cell) {
        if (isValidRecipient(cell)) {
            return "Cell phone number successfully captured.";
        }
        return "Cell phone number is incorrectly formatted or does not contain an international code. "
                + "Please correct the number and try again.";
    }

    public static boolean isValidLength(String text) {
        return text != null && text.length() <= MAX_LENGTH;
    }

    public static String validateLength(String text) {
        if (isValidLength(text)) {
            return "Message ready to send.";
        }
        int over = (text == null ? 0 : text.length()) - MAX_LENGTH;
        return "Message exceeds 250 characters by " + over + "; please reduce the size.";
    }


    public String createMessageHash() {
        String text = messageText == null ? "" : messageText.trim();
        String first = "";
        String last = "";
        if (!text.isEmpty()) {
            String[] words = text.split("\\s+");
            first = clean(words[0]);
            last = clean(words[words.length - 1]);
        }
        String prefix = messageID.length() >= 2 ? messageID.substring(0, 2) : messageID;
        return (prefix + ":" + messageNumber + ":" + first + last).toUpperCase();
    }

    private static String clean(String word) {
        return word.replaceAll("[^A-Za-z0-9]", "");
    }


    
    public String SentMessage(int option) {
        switch (option) {
            case 1:
                sentMessages.add(this);
                registerHashAndID();
                return "Message successfully sent.";
            case 2:
                disregardedMessages.add(this);
                registerHashAndID();
                return "Press 0 to delete the message.";
            case 3:
                storedMessages.add(this);
                registerHashAndID();
                storeMessage();
                return "Message successfully stored.";
            default:
                return "Invalid option. Please choose 1, 2 or 3.";
        }
    }

    private void registerHashAndID() {
        if (!messageHashes.contains(messageHash)) {
            messageHashes.add(messageHash);
        }
        if (!messageIDs.contains(messageID)) {
            messageIDs.add(messageID);
        }
    }


    public static void storeMessage() {
        StringBuilder sb = new StringBuilder("[\n");
        for (int i = 0; i < storedMessages.size(); i++) {
            Message m = storedMessages.get(i);
            sb.append("  {\n")
              .append("    \"messageID\": \"").append(json(m.messageID)).append("\",\n")
              .append("    \"messageNumber\": ").append(m.messageNumber).append(",\n")
              .append("    \"messageHash\": \"").append(json(m.messageHash)).append("\",\n")
              .append("    \"recipient\": \"").append(json(m.recipient)).append("\",\n")
              .append("    \"message\": \"").append(json(m.messageText)).append("\"\n")
              .append("  }").append(i < storedMessages.size() - 1 ? "," : "").append("\n");
        }
        sb.append("]\n");
        try {
            Files.write(storagePath, sb.toString().getBytes(StandardCharsets.UTF_8));
        } catch (IOException e) {
            System.out.println("Could not write JSON file: " + e.getMessage());
        }
    }

    private static String json(String s) {
        StringBuilder out = new StringBuilder();
        for (char c : s.toCharArray()) {
            switch (c) {
                case '"':  out.append("\\\""); break;
                case '\\': out.append("\\\\"); break;
                case '\n': out.append("\\n");  break;
                case '\r': out.append("\\r");  break;
                case '\t': out.append("\\t");  break;
                default:   out.append(c);
            }
        }
        return out.toString();
    }

    private static String unjson(String s) {
        StringBuilder out = new StringBuilder();
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '\\' && i + 1 < s.length()) {
                char n = s.charAt(++i);
                switch (n) {
                    case 'n': out.append('\n'); break;
                    case 'r': out.append('\r'); break;
                    case 't': out.append('\t'); break;
                    default:  out.append(n);
                }
            } else {
                out.append(c);
            }
        }
        return out.toString();
    }


    
    public static int loadStoredMessages() {
        if (!Files.exists(storagePath)) {
            return 0;
        }
        String content;
        try {
            content = new String(Files.readAllBytes(storagePath), StandardCharsets.UTF_8);
        } catch (IOException e) {
            System.out.println("Could not read JSON file: " + e.getMessage());
            return 0;
        }

        int loaded = 0;
        Matcher m = JSON_ENTRY.matcher(content);
        while (m.find()) {
            String id = unjson(m.group(1));
            int number = Integer.parseInt(m.group(2));
            String recipient = unjson(m.group(4));
            String text = unjson(m.group(5));

            boolean alreadyLoaded = false;
            for (Message existing : storedMessages) {
                if (existing.messageID.equals(id)) {
                    alreadyLoaded = true;
                    break;
                }
            }
            if (alreadyLoaded) {
                continue;
            }

            Message loadedMessage = new Message(id, number, recipient, text);
            storedMessages.add(loadedMessage);
            loadedMessage.registerHashAndID();
            if (number >= messageCounter) {
                messageCounter = number + 1;
            }
            loaded++;
        }
        return loaded;
    }


    
    public static String displaySenderAndRecipient() {
        if (storedMessages.isEmpty()) {
            return "There are no stored messages.";
        }
        StringBuilder sb = new StringBuilder();
        for (Message m : storedMessages) {
            sb.append("Sender: ").append(sender)
              .append(" | Recipient: ").append(m.recipient).append("\n");
        }
        return sb.toString().trim();
    }

    
    public static String longestStoredMessage() {
        if (storedMessages.isEmpty()) {
            return "There are no stored messages.";
        }
        Message longest = storedMessages.get(0);
        for (Message m : storedMessages) {
            if (m.messageText.length() > longest.messageText.length()) {
                longest = m;
            }
        }
        return longest.messageText;
    }

    
    public static String searchByMessageID(String id) {
        List<List<Message>> allArrays = new ArrayList<>();
        allArrays.add(sentMessages);
        allArrays.add(storedMessages);
        allArrays.add(disregardedMessages);
        for (List<Message> array : allArrays) {
            for (Message m : array) {
                if (m.messageID.equals(id)) {
                    return "Recipient: " + m.recipient + ", Message: " + m.messageText;
                }
            }
        }
        return "No message found with ID " + id + ".";
    }

    
    public static List<String> searchByRecipient(String cell) {
        List<String> found = new ArrayList<>();
        for (Message m : sentMessages) {
            if (m.recipient.equals(cell)) {
                found.add(m.messageText);
            }
        }
        for (Message m : storedMessages) {
            if (m.recipient.equals(cell)) {
                found.add(m.messageText);
            }
        }
        return found;
    }
    
    public static String deleteByHash(String hash) {
        Iterator<Message> it = storedMessages.iterator();
        while (it.hasNext()) {
            Message m = it.next();
            if (m.messageHash.equalsIgnoreCase(hash)) {
                it.remove();
                messageHashes.remove(m.messageHash);
                messageIDs.remove(m.messageID);
                storeMessage();  
                return "Message: \"" + m.messageText + "\" successfully deleted.";
            }
        }
        return "No stored message found with hash " + hash + ".";
    }

    
    public static String storedMessagesReport() {
        return buildReport("STORED MESSAGES REPORT", storedMessages, "There are no stored messages.");
    }

    
    public static String sentMessagesReport() {
        return buildReport("SENT MESSAGES REPORT", sentMessages, "No messages have been sent yet.");
    }

    private static String buildReport(String title, List<Message> messages, String emptyText) {
        StringBuilder sb = new StringBuilder();
        sb.append("===== ").append(title).append(" =====\n");
        if (messages.isEmpty()) {
            sb.append(emptyText);
            return sb.toString();
        }
        for (Message m : messages) {
            sb.append(m.details()).append("\n\n");
        }
        return sb.toString().trim();
    }


    public String details() {
        return "Message ID: " + messageID + "\n"
             + "Message Hash: " + messageHash + "\n"
             + "Recipient: " + recipient + "\n"
             + "Message: " + messageText;
    }


    public static String printMessages() {
        if (sentMessages.isEmpty()) {
            return "No messages have been sent yet.";
        }
        StringBuilder sb = new StringBuilder();
        for (Message m : sentMessages) {
            sb.append(m.details()).append("\n\n");
        }
        return sb.toString().trim();
    }

    public static int returnTotalMessages() {
        return sentMessages.size();
    }


    public static String generateMessageID() {
        return String.format("%010d", ThreadLocalRandom.current().nextLong(10_000_000_000L));
    }

    public String getMessageID() { return messageID; }
    public int getMessageNumber() { return messageNumber; }
    public String getRecipient() { return recipient; }
    public String getMessageText() { return messageText; }
    public String getMessageHash() { return messageHash; }

    
    public static List<String> getSentMessageTexts() { return texts(sentMessages); }
    public static List<String> getDisregardedMessageTexts() { return texts(disregardedMessages); }
    public static List<String> getStoredMessageTexts() { return texts(storedMessages); }
    public static List<String> getMessageHashes() { return Collections.unmodifiableList(messageHashes); }
    public static List<String> getMessageIDs() { return Collections.unmodifiableList(messageIDs); }

    private static List<String> texts(List<Message> messages) {
        List<String> out = new ArrayList<>();
        for (Message m : messages) {
            out.add(m.messageText);
        }
        return out;
    }

    public static void setStoragePath(Path path) { storagePath = path; }

    public static void setSender(String name) { sender = name; }


    public static void reset() {
        sentMessages.clear();
        disregardedMessages.clear();
        storedMessages.clear();
        messageHashes.clear();
        messageIDs.clear();
        messageCounter = 0;
    }
}